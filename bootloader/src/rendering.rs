fn get_character(ascii_code: u8) -> &'static [u8; 13] {
    if ascii_code <= 32 {
        return &FONT[0];
    }

    return &FONT[(ascii_code - 32) as usize];
}

pub struct DisplayWriter<'a> {
    pub graphics_info: &'a GraphicsInfo,
    pub line:              usize,
    pub col:               usize
}

impl<'a> DisplayWriter<'a> {
    pub fn columns(&self) -> usize {
        self.graphics_info.w / (FONT_WIDTH + HORIZONTAL_SPACING)
    }

    pub fn lines(&self) -> usize {
        self.graphics_info.h / (FONT_HEIGHT + VERTICAL_SPACING)
    }

    pub fn advance_line(&mut self) {
        self.col = 0;
        self.line += 1;

        if self.line >= (self.graphics_info.h / (FONT_HEIGHT + VERTICAL_SPACING)) {
            self.line = 0;
        }
    }

    pub fn advance_column(&mut self) {
        self.col += 1;

        if self.col >= (self.graphics_info.w / (FONT_WIDTH + HORIZONTAL_SPACING)) {
            self.col = 0;
            
            self.advance_line();
        }
    }

    pub fn render_character(&self, character: &[u8; FONT_HEIGHT]) {
        let base_x = self.col * (FONT_WIDTH + HORIZONTAL_SPACING);
        let base_y = self.line * (FONT_HEIGHT + VERTICAL_SPACING);

        for y in 0..FONT_HEIGHT {
            for x in 0..FONT_WIDTH {
                let paint_pixel = (character[(FONT_HEIGHT - 1) - y] & (0b1000_0000 >> x)) != 0;

                unsafe {
                    self.graphics_info.frame_buffer.cast::<u32>().add((base_x + x) + (base_y + y) * self.graphics_info.stride).write_volatile(if paint_pixel { 0xBBBBBBBB } else { 0x00000000 });
                }
            }
        }
    }
}

impl<'a> Write for DisplayWriter<'a> {
    fn write_str(&mut self, s: &str) -> core::fmt::Result {
        for c in s.bytes() {
            if c as char == '\n' {
                while self.col < (self.graphics_info.w / (FONT_WIDTH + HORIZONTAL_SPACING)) {
                    self.render_character(get_character(0));
                    self.col += 1;
                }

                self.advance_line();
                continue;
            }

            let character = get_character(c);

            self.render_character(character);

            self.advance_column();
        }

        Ok(())
    }
}
